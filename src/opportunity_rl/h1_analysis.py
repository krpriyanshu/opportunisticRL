"""Statistics for the H1 learning-curve experiment (docs/evaluation.md
Sections 4, 5 and 8), computed from the `curve_data.json` that
experiments/learning_curve_h1.py writes.

Until this module existed, the reported p-values were computed from
`curve_data.json` by ad hoc analysis that was never committed, so the
headline numbers could not be regenerated by running the repository
(evaluation.md Section 9, "Analysis not scripted"). This module is that
analysis written down, using the scheme evaluation.md Section 4 argues
for:

- The unit of analysis is the matched B4-minus-B2 difference in mean
  evaluation return.
- **Independent units (headline).** learning_curve_h1.py trains ONE PPO
  instance per (severity, seed) and evaluates it at successive budgets,
  so the budgets inside a unit are repeated measures, not independent
  samples. Within each (severity, seed) unit the per-budget differences
  in a regime are averaged to one number, and an exact two-sided sign
  test is applied across units.
- **Pooled (continuity only).** Every (severity, seed, budget) triple
  counted as its own pair. Overstates the effective sample size; kept
  only so figures stay comparable with earlier reporting.

Standard library only (no numpy/scipy), so the analysis has no
dependency beyond the JSON file it reads.
"""

from __future__ import annotations

import math
import statistics
from dataclasses import dataclass
from typing import Any

LOW_BUDGETS: tuple[int, ...] = (10_000, 20_000)
HIGH_BUDGETS: tuple[int, ...] = (40_000, 80_000)


def sign_test_p(n_positive: int, n_negative: int) -> float:
    """Exact two-sided sign test p-value. Ties (zero differences) must
    already be excluded by the caller, which is the standard treatment.
    With no non-tied observations there is no evidence either way: 1.0."""
    n = n_positive + n_negative
    if n == 0:
        return 1.0
    k = min(n_positive, n_negative)
    tail = sum(math.comb(n, i) for i in range(k + 1)) / 2**n
    return min(1.0, 2.0 * tail)


@dataclass(frozen=True)
class SignTestResult:
    n_units: int
    n_favouring_b4: int
    n_favouring_b2: int
    n_ties: int
    p_value: float
    mean_delta: float


def _sign_test(deltas: list[float]) -> SignTestResult:
    pos = sum(1 for d in deltas if d > 0)
    neg = sum(1 for d in deltas if d < 0)
    return SignTestResult(
        n_units=len(deltas),
        n_favouring_b4=pos,
        n_favouring_b2=neg,
        n_ties=len(deltas) - pos - neg,
        p_value=sign_test_p(pos, neg),
        mean_delta=statistics.mean(deltas) if deltas else float("nan"),
    )


@dataclass(frozen=True)
class CurveData:
    """`curve_data.json`, typed. Seeds are ints here even though JSON
    stores them as string keys."""

    budgets: list[int]
    seeds: list[int]
    # returns[disturbance][policy][seed] -> list aligned with `budgets`
    returns: dict[str, dict[str, dict[int, list[float]]]]
    git_commit: str | None = None

    @classmethod
    def from_json(cls, raw: dict[str, Any]) -> CurveData:
        budgets = [int(b) for b in raw["budgets"]]
        returns: dict[str, dict[str, dict[int, list[float]]]] = {}
        for disturbance, per_policy in raw["data"].items():
            returns[disturbance] = {}
            for policy in ("B2", "B4"):
                per_seed = per_policy[policy]
                returns[disturbance][policy] = {
                    int(seed): [float(x) for x in vals] for seed, vals in per_seed.items()
                }
                for seed, vals in returns[disturbance][policy].items():
                    if len(vals) != len(budgets):
                        raise ValueError(
                            f"{disturbance}/{policy}/seed {seed}: {len(vals)} returns "
                            f"for {len(budgets)} budgets"
                        )
        seeds = sorted({s for d in returns.values() for p in d.values() for s in p})
        return cls(budgets=budgets, seeds=seeds, returns=returns, git_commit=raw.get("git_commit"))

    @property
    def disturbances(self) -> list[str]:
        return list(self.returns)

    def delta(self, disturbance: str, seed: int, budget: int) -> float:
        """B4 minus B2 mean evaluation return for one cell."""
        i = self.budgets.index(budget)
        b2 = self.returns[disturbance]["B2"][seed][i]
        b4 = self.returns[disturbance]["B4"][seed][i]
        return b4 - b2

    def matched_seeds(self, disturbance: str) -> list[int]:
        """Seeds present for BOTH policies; an unmatched seed is not a pair."""
        d = self.returns[disturbance]
        return sorted(set(d["B2"]) & set(d["B4"]))


def _regime_budgets(data: CurveData, regime: tuple[int, ...]) -> list[int]:
    present = [b for b in regime if b in data.budgets]
    if not present:
        raise ValueError(f"none of the regime budgets {regime} are in the data {data.budgets}")
    return present


def independent_unit_test(
    data: CurveData, regime: tuple[int, ...], disturbances: list[str] | None = None
) -> SignTestResult:
    """Headline scheme: one averaged difference per (disturbance, seed)."""
    budgets = _regime_budgets(data, regime)
    deltas = []
    for disturbance in disturbances or data.disturbances:
        for seed in data.matched_seeds(disturbance):
            deltas.append(statistics.mean(data.delta(disturbance, seed, b) for b in budgets))
    return _sign_test(deltas)


def pooled_test(data: CurveData, regime: tuple[int, ...]) -> SignTestResult:
    """Continuity scheme: every (disturbance, seed, budget) is one pair."""
    budgets = _regime_budgets(data, regime)
    deltas = [
        data.delta(disturbance, seed, b)
        for disturbance in data.disturbances
        for seed in data.matched_seeds(disturbance)
        for b in budgets
    ]
    return _sign_test(deltas)


@dataclass(frozen=True)
class CellSummary:
    disturbance: str
    budget: int
    mean_b2: float
    mean_b4: float
    mean_delta: float
    n_favouring_b4: int
    n_seeds: int


def cell_summaries(data: CurveData) -> list[CellSummary]:
    """Per (disturbance, budget) means, as in evaluation.md Section 6."""
    out = []
    for disturbance in data.disturbances:
        seeds = data.matched_seeds(disturbance)
        for i, budget in enumerate(data.budgets):
            b2 = [data.returns[disturbance]["B2"][s][i] for s in seeds]
            b4 = [data.returns[disturbance]["B4"][s][i] for s in seeds]
            deltas = [y - x for x, y in zip(b2, b4, strict=True)]
            out.append(
                CellSummary(
                    disturbance=disturbance,
                    budget=budget,
                    mean_b2=statistics.mean(b2),
                    mean_b4=statistics.mean(b4),
                    mean_delta=statistics.mean(deltas),
                    n_favouring_b4=sum(1 for d in deltas if d > 0),
                    n_seeds=len(seeds),
                )
            )
    return out


def format_report(data: CurveData) -> str:
    """Markdown report mirroring evaluation.md Sections 5, 6 and 8."""
    lines: list[str] = []
    lines.append("# H1 analysis")
    lines.append("")
    lines.append(f"Source revision: `{data.git_commit or 'not recorded'}`")
    lines.append(f"Disturbances: {', '.join(data.disturbances)}; seeds: {data.seeds}")
    lines.append(f"Budgets: {data.budgets}")
    lines.append("")

    lines.append("## Sign tests (B4 vs B2)")
    lines.append("")
    lines.append(
        "| Regime | Independent units favouring B4 | p (exact sign test) | Mean Δreturn | Pooled |"
    )
    lines.append("|---|---|---|---|---|")
    for name, regime in (("Low budget", LOW_BUDGETS), ("High budget", HIGH_BUDGETS)):
        try:
            ind = independent_unit_test(data, regime)
            pooled = pooled_test(data, regime)
        except ValueError:
            continue
        lines.append(
            f"| {name} {tuple(b for b in regime if b in data.budgets)} "
            f"| {ind.n_favouring_b4} / {ind.n_units} "
            f"| {ind.p_value:.2g} | {ind.mean_delta:+.3f} "
            f"| {pooled.n_favouring_b4}/{pooled.n_units}, p = {pooled.p_value:.2g} |"
        )
    lines.append("")

    lines.append("## Per-cell mean return, B2 / B4")
    lines.append("")
    lines.append("| Disturbance | " + " | ".join(f"{b // 1000}k" for b in data.budgets) + " |")
    lines.append("|---|" + "---|" * len(data.budgets))
    cells = cell_summaries(data)
    for disturbance in data.disturbances:
        row = [c for c in cells if c.disturbance == disturbance]
        lines.append(
            f"| {disturbance} | "
            + " | ".join(
                f"{c.mean_b2:+.2f} / {c.mean_b4:+.2f} "
                f"(Δ {c.mean_delta:+.2f}, {c.n_favouring_b4}/{c.n_seeds})"
                for c in row
            )
            + " |"
        )
    lines.append("")

    lines.append("## H2: low-budget advantage by disturbance")
    lines.append("")
    lines.append("| Disturbance | Units favouring B4 | p | Mean Δreturn |")
    lines.append("|---|---|---|---|")
    try:
        for disturbance in data.disturbances:
            r = independent_unit_test(data, LOW_BUDGETS, [disturbance])
            lines.append(
                f"| {disturbance} | {r.n_favouring_b4} / {r.n_units} "
                f"| {r.p_value:.2g} | {r.mean_delta:+.3f} |"
            )
    except ValueError:
        lines.append("| (no low-budget data) | | | |")
    lines.append("")
    return "\n".join(lines)
